/**
 * Extends `card-index.ts`, the append-only table that gives every registered
 * card a stable integer for the token policy's embedding table.
 *
 * Why a committed table and not `cardRegistry.keys()` sorted: a sorted index
 * renumbers every card after the one a new set inserts, and a checkpoint's
 * embedding rows are meaningful only under the numbering they were trained
 * against. Appending keeps every existing row where it was, so a checkpoint
 * survives a new set -- the new cards get fresh rows, the old cards keep theirs
 * -- which is the property the roadmap's per-set fine-tune depends on.
 *
 *   pnpm rl:card-index          # append any registry card the table lacks
 *
 * The table is data derived from card numbers alone; it carries no printed
 * text. `test/rl-tokens.test.ts` fails when the registry holds a card the
 * table does not, so a set import that forgets this step goes red rather than
 * silently mapping its cards to the unknown row.
 */
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import { cardRegistry } from "@one-piece-sim/cards";
import { CARD_TABLE_CARDS } from "./card-index.js";
import { missingCardIndexEntries } from "./card-table.js";

const missing = missingCardIndexEntries();
if (missing.length === 0) {
  console.log(
    `card-index.ts already covers all ${cardRegistry.size} registered cards`,
  );
  process.exit(0);
}

// Sorted within the appended batch so a re-run from the same registry is
// byte-identical; the table as a whole stays in append order.
const cards = [...CARD_TABLE_CARDS, ...[...missing].sort()];

const source = `/**
 * Append-only card index for the token policy. Generated by
 * \`pnpm rl:card-index\`; do not edit by hand and never reorder: a checkpoint's
 * embedding rows are indexed by position in this list.
 */
export const CARD_TABLE_CARDS: readonly string[] = ${JSON.stringify(
  cards,
  null,
  2,
)};
`;

const outputPath = join(
  dirname(fileURLToPath(import.meta.url)),
  "card-index.ts",
);
writeFileSync(outputPath, source);
console.log(
  `appended ${missing.length} cards; card-index.ts now holds ${cards.length}`,
);
