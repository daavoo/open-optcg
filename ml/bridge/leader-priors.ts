/**
 * Writes `packages/agents/src/scorer/leader-priors.ts`: per Leader, the
 * expected copies of each card in a list fronted by it, the plain mean over
 * every distinct list we have for that Leader. The compact encoder reads it
 * for the opponent's unseen cards (`leaderPrior`), so the app, training and
 * evaluation all expect the same list.
 *
 *   pnpm exec tsx ml/bridge/leader-priors.ts [scan directory]
 *
 * Lists come from the deck catalog, every training list and variant
 * (`decks.ts`), and the pool scan's tournament lists -- Limitless online and
 * offline, and onepiecetopdecks.com -- that passed `validateDeck` (`ok`). Each
 * distinct (Leader, list) counts once, wherever it was found. Card numbers and
 * counts only: public decklists, no printed text.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { execFileSync } from "node:child_process";
import { deckManifests } from "@one-piece-sim/decks";
import {
  TRAINING_DECK_IDS,
  TRAINING_DECK_VARIANTS,
  trainingManifest,
} from "./decks.js";

const scan = process.argv[2] ?? "ml/checkpoints/pool-scan-2026-10-17";
const OUT = "packages/agents/src/scorer/leader-priors.ts";
/** Below a quarter of a copy is noise from averaging lists that differ; the
    encoder drops it too (`unseen` in compact.ts). */
const FLOOR = 0.25;

const lists = new Map<string, Record<string, number>>();
const counts = { catalog: 0, training: 0, scan: 0 };
const add = (
  leader: string,
  cards: Readonly<Record<string, number>>,
  source: keyof typeof counts,
) => {
  const sorted = Object.fromEntries(
    Object.entries(cards)
      .filter(([, count]) => count > 0)
      .sort(([a], [b]) => a.localeCompare(b)),
  );
  const key = `${leader}|${JSON.stringify(sorted)}`;
  if (lists.has(key)) return;
  lists.set(key, sorted);
  counts[source] += 1;
};

for (const manifest of Object.values(deckManifests))
  add(manifest.leader, manifest.cards, "catalog");
for (const id of [
  ...TRAINING_DECK_IDS,
  ...Object.values(TRAINING_DECK_VARIANTS).flat(),
]) {
  const manifest = trainingManifest(id);
  if (manifest) add(manifest.leader, manifest.cards, "training");
}
for (const file of [
  "scan.json",
  "optd/scan.json",
  "limitless-offline/scan.json",
]) {
  const { rows } = JSON.parse(readFileSync(`${scan}/${file}`, "utf8")) as {
    rows: { leader: string; cards: Record<string, number>; ok: boolean }[];
  };
  for (const row of rows) if (row.ok) add(row.leader, row.cards, "scan");
}

const byLeader = new Map<string, Record<string, number>[]>();
for (const [key, cards] of lists) {
  const leader = key.slice(0, key.indexOf("|"));
  byLeader.set(leader, [...(byLeader.get(leader) ?? []), cards]);
}
const entries: string[] = [];
for (const leader of [...byLeader.keys()].sort()) {
  const group = byLeader.get(leader)!;
  const sum = new Map<string, number>();
  for (const cards of group)
    for (const [number, count] of Object.entries(cards))
      sum.set(number, (sum.get(number) ?? 0) + count);
  const cards = [...sum.keys()]
    .sort()
    .map(
      (number) =>
        [
          number,
          Math.round((sum.get(number)! / group.length) * 100) / 100,
        ] as const,
    )
    .filter(([, copies]) => copies >= FLOOR)
    .map(([number, copies]) => `${number}:${copies}`)
    .join(" ");
  entries.push(`  "${leader}": [${group.length}, "${cards}"],`);
}

writeFileSync(
  OUT,
  `/**
 * Generated by ml/bridge/leader-priors.ts; regenerate rather than edit.
 *
 * Per Leader: how many distinct lists the prior averages, and the expected
 * copies of each card in a list fronted by that Leader, as "number:copies"
 * pairs, cards under ${FLOOR} expected copies left out. The lists are the deck
 * catalog's, the training pool's (ml/bridge/decks.ts) and public tournament
 * results (${counts.catalog} catalog, ${counts.training} more training and ${counts.scan} more tournament lists).
 */
export const LEADER_PRIORS: Readonly<Record<string, readonly [number, string]>> = {
${entries.join("\n")}
};
`,
);
execFileSync("pnpm", ["exec", "prettier", "--write", OUT], {
  stdio: "inherit",
});
process.stderr.write(
  `${byLeader.size} Leaders from ${lists.size} lists (${counts.catalog} catalog, ${counts.training} training, ${counts.scan} scan) -> ${OUT}\n`,
);
