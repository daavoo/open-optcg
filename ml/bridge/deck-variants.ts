/**
 * Real builds of the training decks: other lists players run under the same
 * Leader. Training swaps a drawn deck for one of its variants on a share of
 * games (`compact_ppo --variant-share`), so the model meets the cards those
 * builds play instead of only the one list each deck is registered with -- a
 * card no training list carries is barely learned, and the app pilots
 * whatever list a player brings.
 *
 * A variant resolves like any training deck (`decks.ts`), by its id, which
 * is `<base> ~ <label>`; it is not in `TRAINING_DECK_IDS`, so it never enters
 * the pool on its own, and a game it plays counts towards its base deck.
 */

export interface DeckVariant {
  /** The training deck it is a build of; the Leader is that deck's. */
  base: string;
  label: string;
  cards: Readonly<Record<string, number>>;
  /** Where the list came from: an event and its placing, or who built it. */
  source: string;
}

